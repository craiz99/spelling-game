export function getWordsByZone(zoneId: ZoneId): WordEntry[] {
  return CURRICULUM_WORDS.filter((word) => word.zoneId === zoneId);
}

export function getZoneById(zoneId: ZoneId): ZoneDefinition {
  const found = ZONES.find((z) => z.id === zoneId);
  if (!found) {
    return ZONES[0]!;
  }
  return found;
}

export function getWordById(wordId: string): WordEntry | undefined {
  return CURRICULUM_WORDS.find((word) => word.id === wordId);
}
